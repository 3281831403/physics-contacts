def test_equal_mass_head_on_collision_conserves_momentum():
    bodies = [
        {
            "mass": 2.0,
            "inv_mass": 0.5,
            "pos": [-1.0, 0.0],
            "vel": [3.0, 0.0],
            "radius": 0.5,
            "friction": 0.4,
            "restitution": 0.0,
        },
        {
            "mass": 2.0,
            "inv_mass": 0.5,
            "pos": [1.0, 0.0],
            "vel": [-1.0, 0.0],
            "radius": 0.5,
            "friction": 0.4,
            "restitution": 0.0,
        },
    ]
    contact = {"a": 0, "b": 1, "depth": 0.1, "normal": [1.0, 0.0]}

    result = solve_iterations(bodies, [contact], 8)
    momentum_x = sum(
        body["mass"] * body["vel"][0] for body in result["bodies"]
    )
    momentum_y = sum(
        body["mass"] * body["vel"][1] for body in result["bodies"]
    )

    assert momentum_x == pytest.approx(4.0, abs=1e-6)
    assert momentum_y == pytest.approx(0.0, abs=1e-6)


def test_contact_input_order_does_not_change_solver_result():
    bodies = [
        {
            "mass": 1.0,
            "inv_mass": 1.0,
            "pos": [-0.5, 0.0],
            "vel": [0.0, 0.0],
            "radius": 0.5,
            "friction": 0.5,
            "restitution": 0.0,
        },
        {
            "mass": 1.0,
            "inv_mass": 1.0,
            "pos": [0.5, 0.0],
            "vel": [0.0, 0.0],
            "radius": 0.5,
            "friction": 0.5,
            "restitution": 0.0,
        },
        {
            "mass": 1.0,
            "inv_mass": 1.0,
            "pos": [1.5, 0.0],
            "vel": [0.0, 0.0],
            "radius": 0.5,
            "friction": 0.5,
            "restitution": 0.0,
        },
    ]
    contact_01 = {"a": 0, "b": 1, "depth": 0.03, "normal": [1.0, 0.0]}
    contact_12 = {"a": 1, "b": 2, "depth": 0.07, "normal": [1.0, 0.0]}
    contact_02 = {"a": 0, "b": 2, "depth": 0.05, "normal": [1.0, 0.0]}

    first = detect([contact_12, contact_01, contact_02], bodies, 0.0)
    second = detect([contact_02, contact_12, contact_01], bodies, 0.0)

    signature = lambda items: [
        (item["a"], item["b"], item["depth"]) for item in items
    ]
    assert signature(first) == signature(second)

    first_result = solve_iterations(copy.deepcopy(bodies), first, 8)
    second_result = solve_iterations(copy.deepcopy(bodies), second, 8)
    for body_a, body_b in zip(first_result["bodies"], second_result["bodies"]):
        assert body_a["pos"] == pytest.approx(body_b["pos"], abs=1e-6)
        assert body_a["vel"] == pytest.approx(body_b["vel"], abs=1e-6)


