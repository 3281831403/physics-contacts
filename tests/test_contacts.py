def test_substep_dt_scales_with_substep_count():
    bodies_one = [
        {
            "mass": 1.0,
            "inv_mass": 1.0,
            "pos": [0.0, 0.0],
            "vel": [1.5, -0.5],
            "radius": 0.5,
            "friction": 0.5,
            "restitution": 0.0,
        }
    ]
    bodies_four = [
        {
            "mass": 1.0,
            "inv_mass": 1.0,
            "pos": [0.0, 0.0],
            "vel": [1.5, -0.5],
            "radius": 0.5,
            "friction": 0.5,
            "restitution": 0.0,
        }
    ]

    one_step = step_batch(bodies_one, [], 1)
    four_steps = step_batch(bodies_four, [], 4)

    assert one_step["bodies"][0]["pos"] == pytest.approx(
        [1.5 / 60.0, -0.5 / 60.0], abs=1e-6
    )
    assert four_steps["bodies"][0]["pos"] == pytest.approx(
        one_step["bodies"][0]["pos"], abs=1e-6
    )


